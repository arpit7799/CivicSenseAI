# CivicSense AI — Application-Side Anti-Hallucination Guardrails
# =============================================================================
# Enforces strict application-level validation on LLM output.
#
# CRITICAL SOURCE INTEGRITY:
# - A prompt is NOT a security boundary.
# - Official contact info must come exclusively from verified authority records.
# - Any unverified email, phone number, or invented statutory deadline
#   causes validation failure, triggering the independent deterministic fallback.
#
# Owner: Arpit (Person 1)
# =============================================================================

import re
from typing import Any

from app.core.logging import get_logger

logger = get_logger(__name__)

# Patterns for detecting phone numbers and email addresses
EMAIL_REGEX = re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,}\b")
# Common phone patterns: 10-12 digits with optional separators/country code
PHONE_REGEX = re.compile(r"(?:\+91[\-\s]?)?[6-9]\d{9}\b|\b\d{3}[-.\s]\d{3}[-.\s]\d{4}\b")
# Patterns for fabricated statutory/penal deadlines (e.g. "within 24 hours under Section 14")
STATUTORY_DEADLINE_REGEX = re.compile(
    r"\b(?:within\s+\d+\s+(?:hours?|days?)\s+under\s+(?:section|act|bylaw|rule)|"
    r"section\s+\d+\s+of\s+the\s+[A-Za-z\s]+act|penalty\s+of\s+(?:rs\.?|inr)\s*\d+)",
    re.IGNORECASE,
)


class GuardrailViolationError(ValueError):
    """Raised when generated complaint text violates anti-hallucination policies."""
    pass


def validate_and_sanitize_complaint(data: dict[str, Any], context: dict[str, Any]) -> dict[str, Any]:
    """
    Validate LLM output against verified decision context.

    Raises GuardrailViolationError if:
    - Missing required schema fields
    - Fabricated email address not present in verified records
    - Fabricated phone number not present in verified records
    - Fabricated statutory deadline or legal section not present in RAG docs
    """
    # 1. Structural schema validation
    for field in ("subject", "body", "requested_action"):
        val = data.get(field)
        if not val or not isinstance(val, str) or not val.strip():
            raise GuardrailViolationError(f"Field '{field}' must be a non-empty string")

    # 2. Priority validation & synchronization
    expected_severity = context.get("severity_level", "MEDIUM").upper()
    priority = str(data.get("priority", expected_severity)).upper()
    if priority not in ("LOW", "MEDIUM", "HIGH", "CRITICAL"):
        priority = expected_severity
    # Always enforce that priority matches the assessed severity
    data["priority"] = expected_severity

    full_text = f"{data['subject']} {data['body']} {data.get('requested_action', '')}"

    # 3. Verified Contact Information Validation
    verified_emails = set()
    if context.get("contact_email"):
        verified_emails.add(context["contact_email"].lower())

    verified_phones = set()
    if context.get("contact_phone"):
        # Strip spaces and dashes for clean comparison
        clean_phone = re.sub(r"[\s\-\+]", "", str(context["contact_phone"]))
        verified_phones.add(clean_phone)

    # Check for emails
    found_emails = EMAIL_REGEX.findall(full_text)
    for email in found_emails:
        if email.lower() not in verified_emails:
            logger.warning(f"Hallucination detected: unverified email '{email}' generated by LLM")
            raise GuardrailViolationError(f"Generated text contains unverified email address: '{email}'")

    # Check for phone numbers
    found_phones = PHONE_REGEX.findall(full_text)
    for phone in found_phones:
        clean_found = re.sub(r"[\s\-\+]", "", phone)
        # Check against verified phone suffix (e.g. last 10 digits)
        matched = any(clean_found.endswith(vp[-10:]) or vp.endswith(clean_found[-10:]) for vp in verified_phones)
        if not matched:
            logger.warning(f"Hallucination detected: unverified phone '{phone}' generated by LLM")
            raise GuardrailViolationError(f"Generated text contains unverified phone number: '{phone}'")

    # 4. Statutory Deadline and Legal Claims Validation
    # If the LLM generates specific statutory claims or penal timelines,
    # verify that they are mentioned in the retrieved RAG documents.
    rag_docs = " ".join(context.get("rag_documents", []))
    statutory_matches = STATUTORY_DEADLINE_REGEX.findall(full_text)
    for match in statutory_matches:
        if match.lower() not in rag_docs.lower():
            logger.warning(f"Hallucination detected: unsupported statutory claim '{match}'")
            raise GuardrailViolationError(
                f"Generated text contains unsupported statutory/procedural deadline: '{match}'"
            )

    return data
